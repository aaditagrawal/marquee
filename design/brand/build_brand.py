"""Generate every Marquee brand asset from the mark's geometry (design/brand/mark.py).

One colour on one ground: ink #0B0B0C and paper #FAFAF8. The same drawing becomes the
Android launcher icon and TV banner, the favicon set, the logo lockups and the social cards.

Run from the repository root:

    uv run --no-project --with cairosvg --with fonttools --with uharfbuzz \
        --with shapely --with pillow python design/brand/build_brand.py

Options:
    --kit-only         write design/brand/ only, leave app resources alone
    --app-root PATH    write the Android resources into another checkout's app/ folder
    --icon-glyph reel  use the reel alone as the launcher icon foreground
"""
from __future__ import annotations

import argparse
import io
import json
import pathlib
import sys

import cairosvg
from PIL import Image
from shapely import affinity
from shapely.geometry import LineString

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(ROOT / "design/icon"))
import build_icons as bi  # noqa: E402  (scene model, VectorDrawable/SVG writers, wordmark outlines)
import mark  # noqa: E402

INK, PAPER = "#0B0B0C", "#FAFAF8"
FONT_REGULAR = ROOT / "design/fonts/hanken_grotesk_regular.ttf"
TAGLINE = "A native Jellyfin client for Android TV"


# ---------------------------------------------------------------- helpers
def place(geom, cx, cy, diameter, *, tolerance=0.012):
    """Scale the 100-unit mark so its 90-unit disc has `diameter`, centred on (cx, cy)."""
    k = diameter / (2 * mark.RADIUS)
    g = affinity.scale(geom, xfact=k, yfact=k, origin=(50, 50))
    return affinity.translate(g, cx - 50, cy - 50).simplify(tolerance * diameter / 90, preserve_topology=True)


def add(scene, geom, fill):
    """Add `geom` to the scene one polygon per path. Android's resource table cannot hold a
    string over 32 KiB, and one path for the whole mark is larger than that."""
    for poly in getattr(geom, "geoms", [geom]):
        d = bi.poly_d(poly)
        if d:
            assert len(d) < 30000, "path too long for an Android resource string"
            scene.add(d, fill)


def text_path(text, size, x, baseline, font=None, tracking=-0.025):
    old = bi.FONT
    bi.FONT = font or old
    try:
        return bi.wordmark_path(text, size, x, baseline, tracking_em=tracking)
    finally:
        bi.FONT = old


def cap(size):
    return bi.text_metrics(size)[0]


def png(svg: str, w: int, h: int | None = None) -> bytes:
    return cairosvg.svg2png(bytestring=svg.encode(), output_width=w, output_height=h or w)


def save(path: pathlib.Path, data, root=ROOT):
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        path.write_text(data)
    else:
        path.write_bytes(data)
    try:
        print("wrote", path.relative_to(root))
    except ValueError:
        print("wrote", path)


EMBLEM = mark.emblem()
REEL = mark.reel()


def tile(size, fg, bg, glyph=EMBLEM, fill=0.80) -> bi.Scene:
    """Square ground with the mark. `fill` is mark diameter / tile size."""
    s = bi.Scene(size, size)
    if bg:
        s.add(bi.rect_d(0, 0, size, size), bi.Solid(bg))
    add(s, place(glyph, size / 2, size / 2, size * fill), bi.Solid(fg))
    return s


def tile_svg(px, fg=PAPER, bg=INK, glyph=EMBLEM, fill=0.80, radius=0.0, circle=False):
    s = tile(100.0, fg, bg, glyph, fill)
    return bi.to_svg(s, px, px, clip_radius=(100 * radius) if radius else None, clip_circle=circle)


def lockup_scene(fg, glyph=EMBLEM) -> bi.Scene:
    h = 100.0
    fsize = 100.0 * 36 / cap(100.0)
    _, w = text_path("Marquee", fsize, 0, 0)
    s = bi.Scene(h + 18 + w + 4, h)
    add(s, place(glyph, 50, 50, 92), bi.Solid(fg))
    d, _ = text_path("Marquee", fsize, h + 18, 50 + cap(fsize) / 2)
    s.add(d, bi.Solid(fg))
    return s


# ---------------------------------------------------------------- Android resources
IC = 108.0


def android(app: pathlib.Path, root: pathlib.Path, icon_glyph: str = "mark"):
    res = app / "src/main/res"
    bg = bi.Scene(IC, IC)
    bg.add(bi.rect_d(0, 0, IC, IC), bi.Solid(INK))
    fg = bi.Scene(IC, IC)
    # 62dp across: inside the 66dp adaptive safe circle, and large in launcher rows that
    # show the foreground on its own.
    if icon_glyph == "reel":   # launchers that show a small one-colour glyph beside the app name
        add(fg, place(REEL, IC / 2, IC / 2, 58), bi.Solid(PAPER))
    else:
        add(fg, place(EMBLEM, IC / 2, IC / 2, 62, tolerance=0.035), bi.Solid(PAPER))
    note = "<!-- Generated by design/brand/build_brand.py. Edit the script, not this file. -->"

    def vec(scene, w, h):
        return bi.to_vector(scene, w, h).replace(
            "<!-- Generated by design/icon/build_icons.py. Edit the script, not this file. -->", note)

    save(res / "drawable/ic_launcher_background.xml", vec(bg, IC, IC), root)
    save(res / "drawable/ic_launcher_foreground.xml", vec(fg, IC, IC), root)
    save(res / "mipmap-anydpi-v26/ic_launcher.xml",
         '<?xml version="1.0" encoding="utf-8"?>\n'
         "<!-- Generated by design/brand/build_brand.py. -->\n"
         '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
         '    <background android:drawable="@drawable/ic_launcher_background" />\n'
         '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
         '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
         "</adaptive-icon>\n", root)
    legacy = tile_svg(96, glyph=REEL, radius=0.2, fill=0.72) if icon_glyph == "reel" else tile_svg(96, radius=0.2, fill=0.78)
    save(res / "mipmap-xhdpi/ic_launcher.png", png(legacy, 96), root)
    # Android TV banners use 320 x 180 pixels at xhdpi. Render each density from the same
    # scene so the launcher does not have to tessellate the lattice and wordmark.
    for variant, is_debug in (("main", False), ("debug", True)):
        scene = banner(dev=is_debug)
        variant_res = app / f"src/{variant}/res"
        for density, width in (("mdpi", 160), ("hdpi", 240), ("xhdpi", 320), ("xxhdpi", 480), ("xxxhdpi", 640)):
            height = width * 9 // 16
            image = png(bi.to_svg(scene, width, height), width, height)
            save(variant_res / f"drawable-{density}/banner.png", image, root)
        # Remove the preceding generated vector when regenerating an older checkout.
        previous = variant_res / ("drawable-xhdpi" if is_debug else "drawable") / "banner.xml"
        if previous.is_file() and note in previous.read_text():
            previous.unlink()


BW, BH = 640.0, 360.0


def banner(dev=False) -> bi.Scene:
    """Android TV banner, 320 x 180 dp: mark and wordmark, paper on ink."""
    s = bi.Scene(BW, BH)
    s.add(bi.rect_d(0, 0, BW, BH), bi.Solid(INK))
    d_mark = 196.0
    fsize = 100.0 * 62 / cap(100.0)
    _, w = text_path("Marquee", fsize, 0, 0)
    gap = 34.0
    left = (BW - (d_mark + gap + w)) / 2
    add(s, place(EMBLEM, left + d_mark / 2, BH / 2, d_mark), bi.Solid(PAPER))
    d, _ = text_path("Marquee", fsize, left + d_mark + gap, BH / 2 + cap(fsize) / 2)
    s.add(d, bi.Solid(PAPER))
    if dev:  # debug builds: a DEV tab in the top-right corner
        pill = LineString([(520, 48), (584, 48)]).buffer(20, quad_segs=12)
        s.add(bi.poly_d(pill), bi.Solid(PAPER))
        _, dw = text_path("DEV", 26.0, 0, 0, tracking=0.05)
        d, _ = text_path("DEV", 26.0, 552 - dw / 2, 48 + cap(26.0) / 2, tracking=0.05)
        s.add(d, bi.Solid(INK))
    return s


# ---------------------------------------------------------------- web kit
def favicons(out: pathlib.Path):
    r = 0.22
    # 16 to 32 px: the reel alone. From 48 px the full mark holds.
    save(out / "favicon.svg", tile_svg(64, glyph=REEL, fill=0.74, radius=r))
    frames = {}
    for n in (16, 32):
        frames[n] = png(tile_svg(n, glyph=REEL, fill=0.78 if n == 16 else 0.74, radius=r), n)
    for n in (48, 96):
        frames[n] = png(tile_svg(n, fill=0.84, radius=r), n)
    for n, data in frames.items():
        save(out / f"favicon-{n}.png", data)
    ico = io.BytesIO()
    imgs = [Image.open(io.BytesIO(frames[n])).convert("RGBA") for n in (16, 32, 48)]
    imgs[-1].save(ico, format="ICO", append_images=imgs[:-1], sizes=[(48, 48), (16, 16), (32, 32)])
    save(out / "favicon.ico", ico.getvalue())
    save(out / "apple-touch-icon.png", png(tile_svg(180, fill=0.78), 180))
    for n in (192, 512):
        save(out / f"icon-{n}.png", png(tile_svg(n, fill=0.80, radius=r), n))
        save(out / f"icon-maskable-{n}.png", png(tile_svg(n, fill=0.66), n))
    save(out / "icon-round-512.png", png(tile_svg(512, fill=0.78, circle=True), 512))
    save(out / "mask-icon.svg", bi.to_svg(tile(16.0, "#000000", None, REEL, 0.92), 16, 16))
    manifest = {
        "name": "Marquee", "short_name": "Marquee", "description": TAGLINE,
        "icons": [
            {"src": "icon-192.png", "sizes": "192x192", "type": "image/png", "purpose": "any"},
            {"src": "icon-512.png", "sizes": "512x512", "type": "image/png", "purpose": "any"},
            {"src": "icon-maskable-192.png", "sizes": "192x192", "type": "image/png", "purpose": "maskable"},
            {"src": "icon-maskable-512.png", "sizes": "512x512", "type": "image/png", "purpose": "maskable"},
        ],
        "theme_color": INK, "background_color": INK, "display": "standalone",
    }
    save(out / "site.webmanifest", json.dumps(manifest, indent=2) + "\n")
    save(out / "head.html", "\n".join([
        "<!-- Marquee favicon set. Copy design/brand/favicon/* to the site root. -->",
        '<link rel="icon" href="/favicon.ico" sizes="48x48">',
        '<link rel="icon" href="/favicon.svg" type="image/svg+xml">',
        '<link rel="apple-touch-icon" href="/apple-touch-icon.png">',
        f'<link rel="mask-icon" href="/mask-icon.svg" color="{INK}">',
        '<link rel="manifest" href="/site.webmanifest">',
        f'<meta name="theme-color" content="{INK}">',
        "",
    ]))


def logos(out: pathlib.Path):
    for name, fg in (("on-light", INK), ("on-dark", PAPER)):
        s = lockup_scene(fg)
        svg = bi.to_svg(s, round(96 * s.w / s.h), 96).replace(
            "<svg ", '<svg role="img" aria-label="Marquee" ', 1)
        save(out / f"lockup-{name}.svg", svg)
        save(out / f"lockup-{name}.png", png(svg, round(192 * s.w / s.h), 192))
        for glyph, gname in ((EMBLEM, "mark"), (REEL, "reel")):
            m = tile(100.0, fg, None, glyph, 0.92 if glyph is EMBLEM else 0.90)
            save(out / f"{gname}-{name}.svg", bi.to_svg(m, 512, 512))
            if glyph is EMBLEM:
                save(out / f"{gname}-{name}.png", png(bi.to_svg(m, 1024, 1024), 1024))
    save(out / "tile.svg", tile_svg(512, radius=0.22))
    save(out / "tile-1024.png", png(tile_svg(1024, radius=0.22), 1024))


def card(w, h) -> bi.Scene:
    s = bi.Scene(w, h)
    s.add(bi.rect_d(0, 0, w, h), bi.Solid(INK))
    d_mark = h * 0.50
    fsize = 100.0 * (h * 0.150) / cap(100.0)
    _, word_w = text_path("Marquee", fsize, 0, 0)
    gap = h * 0.085
    left = (w - (d_mark + gap + word_w)) / 2
    cy = h * 0.455
    add(s, place(EMBLEM, left + d_mark / 2, cy, d_mark), bi.Solid(PAPER))
    d, _ = text_path("Marquee", fsize, left + d_mark + gap, cy + cap(fsize) / 2)
    s.add(d, bi.Solid(PAPER))
    tsize = h * 0.052
    _, tw = text_path(TAGLINE, tsize, 0, 0, font=FONT_REGULAR, tracking=0.0)
    d, _ = text_path(TAGLINE, tsize, (w - tw) / 2, h * 0.865, font=FONT_REGULAR, tracking=0.0)
    s.add(d, bi.Solid(PAPER, 0.62))
    return s


def social(out: pathlib.Path):
    for name, (w, h) in {"github-social-preview-1280x640": (1280, 640), "og-1200x630": (1200, 630)}.items():
        save(out / f"{name}.png", png(bi.to_svg(card(w, h), w, h), w, h))
    save(out / "github-social-preview.svg", bi.to_svg(card(1280, 640), 1280, 640))


def sheet(out: pathlib.Path):
    W, H = 1600, 1240
    im = Image.new("RGB", (W, H), PAPER)
    im.paste(Image.new("RGB", (W // 2, H), "#111112"), (W // 2, 0))

    def put(src, x, y, size=None, resample=Image.LANCZOS):
        a = (Image.open(src) if isinstance(src, pathlib.Path) else Image.open(io.BytesIO(src))).convert("RGBA")
        if size:
            a = a.resize(size, resample)
        im.paste(a, (x, y), a)

    fav, logo = HERE / "favicon", HERE / "logo"
    for col, (x0, name) in enumerate(((60, "on-light"), (W // 2 + 60, "on-dark"))):
        put(logo / f"mark-{name}.png", x0, 40, (380, 380))
        x = x0 + 420
        for n in (16, 32, 48, 96):
            put(fav / f"favicon-{n}.png", x, 60 + (96 - n))
            x += n + 22
        put(fav / "favicon-16.png", x0 + 420, 190, (128, 128), Image.NEAREST)
        put(fav / "favicon-32.png", x0 + 570, 190, (128, 128), Image.NEAREST)
        put(logo / f"lockup-{name}.png", x0, 470, None)
        put(fav / "icon-512.png", x0, 720, (150, 150))
        put(fav / "icon-round-512.png", x0 + 175, 720, (150, 150))
        put(fav / "apple-touch-icon.png", x0 + 350, 720, (150, 150))
    put(png(bi.to_svg(banner(), 640, 360), 640, 360), 60, 900, (533, 300))
    put(HERE / "social/github-social-preview-1280x640.png", W // 2 + 60, 900, (600, 300))
    im.save(out)
    print("wrote", out.relative_to(ROOT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kit-only", action="store_true")
    ap.add_argument("--app-root", type=pathlib.Path, help="another checkout's app/ directory")
    ap.add_argument("--icon-glyph", choices=("mark", "reel"), default="mark",
                    help="launcher icon foreground: the full mark (default) or the reel alone")
    args = ap.parse_args()
    if args.app_root:
        android(args.app_root.resolve(), args.app_root.resolve().parent, args.icon_glyph)
        return
    if not args.kit_only:
        android(ROOT / "app", ROOT, args.icon_glyph)
    favicons(HERE / "favicon")
    logos(HERE / "logo")
    social(HERE / "social")
    sheet(HERE / "sheet.png")


if __name__ == "__main__":
    main()
