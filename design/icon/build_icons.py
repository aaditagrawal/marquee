"""Generate Marquee's launcher icon and Android TV banner from one geometry source.

The artwork is a set of filled paths (solid, linear or radial gradient). The same
scene is written as Android VectorDrawable XML (shipped in the app) and as SVG
(rasterised to PNG for previews and the legacy launcher icon).

This module is now a library: design/brand/build_brand.py imports its scene model,
exporters and wordmark outlining to generate the current "reel lattice" identity.
The folded-light drawing below is retired and kept for reference.

The mark (round 3, "folded light") is a single ribbon folded into an M: two lit
stems and two shaded folds meeting at the baseline, under a blue key light
with a cool backlight behind it.

The wordmark is outlined from Hanken Grotesk SemiBold (SIL OFL 1.1, design/fonts/OFL.txt).
No font file is added to the APK by this script; only vector outlines of the glyphs.

"""
from __future__ import annotations

import argparse
import pathlib
import sys
from dataclasses import dataclass, field

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from shapely.geometry import LineString, box
from shapely.geometry.polygon import orient

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent  # repository root
RES = ROOT / "app/src/main/res"
FONT = ROOT / "design/fonts/hanken_grotesk_semibold.ttf"

# ---------------------------------------------------------------- palette
# Derived from design/DESIGN.md: MaxioBlue #0042FF as the cool house light,
# Yellow #FFE246 / Amber #FFAB41 warmth for the mark, clay-2 #F8F7F7 text.
# The mark's face tones live with its geometry in FACES below.
NIGHT = "#06071C"        # deep blue-black base (not pure black: avoids LCD crush)
BLUE = "#0042FF"         # MaxioBlue
WORD = "#F8F7F7"


# ---------------------------------------------------------------- scene model
@dataclass
class Solid:
    color: str
    alpha: float = 1.0


@dataclass
class Linear:
    x1: float
    y1: float
    x2: float
    y2: float
    stops: list  # [(offset, "#RRGGBB", alpha)]


@dataclass
class Radial:
    cx: float
    cy: float
    r: float
    stops: list


@dataclass
class Shape:
    d: str
    fill: object


@dataclass
class Scene:
    w: float
    h: float
    shapes: list = field(default_factory=list)

    def add(self, d, fill):
        self.shapes.append(Shape(d, fill))


def fmt(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def rect_d(x, y, w, h):
    return f"M{fmt(x)},{fmt(y)}H{fmt(x + w)}V{fmt(y + h)}H{fmt(x)}Z"


def circle_d(cx, cy, r):
    return (f"M{fmt(cx - r)},{fmt(cy)}A{fmt(r)},{fmt(r)} 0 1,0 {fmt(cx + r)},{fmt(cy)}"
            f"A{fmt(r)},{fmt(r)} 0 1,0 {fmt(cx - r)},{fmt(cy)}Z")


def poly_d(geom) -> str:
    """Shapely (Multi)Polygon -> path data. Holes are emitted reversed for nonzero fill."""
    polys = getattr(geom, "geoms", [geom])
    out = []
    for p in polys:
        if p.geom_type != "Polygon" or p.area < 1e-3:
            continue  # boolean ops can leave slivers, lines or points
        p = orient(p, 1.0)
        rings = [p.exterior.coords] + [i.coords for i in p.interiors]
        for ring in rings:
            pts = list(ring)[:-1]
            out.append("M" + "L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts) + "Z")
    return "".join(out)


# ---------------------------------------------------------------- exporters
def _hex8(color: str, alpha: float) -> str:
    a = max(0, min(255, round(alpha * 255)))
    return f"#{a:02X}{color.lstrip('#').upper()}"


def to_vector(scene: Scene, width_dp: float, height_dp: float) -> str:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by design/icon/build_icons.py. Edit the script, not this file. -->",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        '    xmlns:aapt="http://schemas.android.com/aapt"',
        f'    android:width="{fmt(width_dp)}dp"',
        f'    android:height="{fmt(height_dp)}dp"',
        f'    android:viewportWidth="{fmt(scene.w)}"',
        f'    android:viewportHeight="{fmt(scene.h)}">',
    ]
    for s in scene.shapes:
        f = s.fill
        if isinstance(f, Solid):
            lines.append(f'    <path android:fillColor="{_hex8(f.color, f.alpha)}"')
            lines.append(f'        android:pathData="{s.d}" />')
            continue
        lines.append(f'    <path android:pathData="{s.d}">')
        lines.append('        <aapt:attr name="android:fillColor">')
        if isinstance(f, Linear):
            lines.append(f'            <gradient android:type="linear" android:startX="{fmt(f.x1)}" '
                         f'android:startY="{fmt(f.y1)}" android:endX="{fmt(f.x2)}" android:endY="{fmt(f.y2)}">')
        else:
            lines.append(f'            <gradient android:type="radial" android:centerX="{fmt(f.cx)}" '
                         f'android:centerY="{fmt(f.cy)}" android:gradientRadius="{fmt(f.r)}">')
        for off, col, a in f.stops:
            lines.append(f'                <item android:offset="{fmt(off)}" android:color="{_hex8(col, a)}" />')
        lines.append("            </gradient>")
        lines.append("        </aapt:attr>")
        lines.append("    </path>")
    lines.append("</vector>")
    return "\n".join(lines) + "\n"


def to_svg(scene: Scene, out_w: int, out_h: int, clip_radius: float | None = None,
           clip_circle: bool = False, view: tuple | None = None) -> str:
    defs, body = [], []
    for i, s in enumerate(scene.shapes):
        f = s.fill
        if isinstance(f, Solid):
            body.append(f'<path d="{s.d}" fill="{f.color}" fill-opacity="{f.alpha}"/>')
            continue
        gid = f"g{i}"
        stops = "".join(f'<stop offset="{o}" stop-color="{c}" stop-opacity="{a}"/>' for o, c, a in f.stops)
        if isinstance(f, Linear):
            defs.append(f'<linearGradient id="{gid}" gradientUnits="userSpaceOnUse" x1="{f.x1}" '
                        f'y1="{f.y1}" x2="{f.x2}" y2="{f.y2}">{stops}</linearGradient>')
        else:
            defs.append(f'<radialGradient id="{gid}" gradientUnits="userSpaceOnUse" cx="{f.cx}" '
                        f'cy="{f.cy}" r="{f.r}">{stops}</radialGradient>')
        body.append(f'<path d="{s.d}" fill="url(#{gid})"/>')
    clip_open = clip_close = ""
    if clip_radius is not None or clip_circle:
        if clip_circle:
            defs.append(f'<clipPath id="clip"><circle cx="{scene.w / 2}" cy="{scene.h / 2}" r="{scene.w / 2}"/></clipPath>')
        else:
            defs.append(f'<clipPath id="clip"><rect width="{scene.w}" height="{scene.h}" '
                        f'rx="{clip_radius}" ry="{clip_radius}"/></clipPath>')
        clip_open, clip_close = '<g clip-path="url(#clip)">', "</g>"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{out_w}" height="{out_h}" '
            f'viewBox="{" ".join(fmt(v) for v in (view or (0, 0, scene.w, scene.h)))}"><defs>{"".join(defs)}</defs>'
            f'{clip_open}{"".join(body)}{clip_close}</svg>')


def merge(*scenes: Scene) -> Scene:
    s = Scene(scenes[0].w, scenes[0].h)
    for sc in scenes:
        s.shapes.extend(sc.shapes)
    return s


# ---------------------------------------------------------------- the mark
# Round 3, "folded light": one ribbon folded into an M, lit from the upper left.
# Four flat faces give the depth; the silhouette alone still reads at launcher-card size.
# Everything is proportional to the mark height, so all sizes share one drawing.
MARK_ASPECT = 1.14        # width / height
STEM = 0.245              # stem width / mark width
V_DEPTH = 0.80            # V centreline depth; its underside lands on the baseline
ROUND_OUT = 0.15          # convex corner radius / stem width
ROUND_IN = 0.07           # concave corner radius / stem width

FACES = (  # (name, top -> bottom stops). Lit stem, two shaded folds, half-lit stem.
    ("stem_l", [(0, "#FFF5DA", 1), (0.45, "#FFDB8E", 1), (1, "#FFB443", 1)]),
    ("fold_l", [(0, "#F2A54C", 1), (1, "#B04E17", 1)]),
    ("fold_r", [(0, "#B5591F", 1), (1, "#6B280B", 1)]),
    ("stem_r", [(0, "#FFD67E", 1), (1, "#E2852A", 1)]),
)


def _soften(g, r_out, r_in):
    g = g.buffer(-r_out, join_style="round", quad_segs=10).buffer(r_out, join_style="round", quad_segs=10)
    return g.buffer(r_in, join_style="round", quad_segs=10).buffer(-r_in, join_style="round", quad_segs=10)


def mark_geometry(cx: float, cy: float, h: float):
    """Return (silhouette, [(face name, polygon)]) for an M of height `h`."""
    w = h * MARK_ASPECT
    x0, y0, x1, y1 = cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2
    t = w * STEM
    half = t / 2
    centre = [(x0 + half, y1), (x0 + half, y0 + half), (cx, y0 + h * V_DEPTH),
              (x1 - half, y0 + half), (x1 - half, y1)]
    ribbon = LineString(centre).buffer(half, cap_style="flat", join_style="mitre", mitre_limit=8)
    ribbon = _soften(ribbon.intersection(box(x0, y0, x1, y1)), t * ROUND_OUT, t * ROUND_IN)
    # Folds run vertically down the inner edge of each stem, and down the centre.
    inner = box(x0 + t, y0 - 1, x1 - t, y1 + 1)
    left = box(x0 - 1, y0 - 1, cx, y1 + 1)
    stems, folds = ribbon.difference(inner), ribbon.intersection(inner)
    faces = [("stem_l", stems.intersection(left)), ("fold_l", folds.intersection(left)),
             ("fold_r", folds.difference(left)), ("stem_r", stems.difference(left))]
    return ribbon, faces


def draw_mark(scene: Scene, cx, cy, h):
    ribbon, faces = mark_geometry(cx, cy, h)
    top, bottom = cy - h / 2, cy + h / 2
    tones = dict(FACES)
    # The whole silhouette first, in a mid tone, so antialiased seams never show the sky.
    scene.add(poly_d(ribbon), Solid("#C8661F"))
    for name, geom in faces:
        scene.add(poly_d(geom), Linear(cx, top, cx, bottom, tones[name]))
    return ribbon


def mark_mono(scene: Scene, cx, cy, h, color, alpha=1.0):
    ribbon, _ = mark_geometry(cx, cy, h)
    scene.add(poly_d(ribbon), Solid(color, alpha))


def stage(scene: Scene, key_at, key_r, back_at, back_r):
    """Ink-blue house dark, a MaxioBlue key from above, a cooler backlight behind the mark.

    A warm halo was tried and went muddy brown over the blue; a cool backlight
    separates the gold mark more cleanly.
    """
    w, h = scene.w, scene.h
    scene.add(rect_d(0, 0, w, h), Linear(0, 0, w * 0.25, h, [(0, "#0B1031", 1), (1, NIGHT, 1)]))
    kx, ky = key_at
    scene.add(rect_d(0, 0, w, h), Radial(kx, ky, key_r, [(0, BLUE, 0.62), (0.5, BLUE, 0.18), (1, BLUE, 0)]))
    bx, by = back_at
    scene.add(rect_d(0, 0, w, h), Radial(bx, by, back_r, [(0, "#3A6BFF", 0.40), (0.5, "#3A6BFF", 0.12), (1, "#3A6BFF", 0)]))


# ---------------------------------------------------------------- wordmark
def wordmark_path(text: str, size: float, x: float, baseline: float, tracking_em: float = -0.02):
    """Shape `text` with HarfBuzz (kerning on) and return (path data, advance width)."""
    blob = hb.Blob(FONT.read_bytes())
    face = hb.Face(blob)
    font = hb.Font(face)
    upem = face.upem
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})
    tt = TTFont(str(FONT))
    gs = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    scale = size / upem
    pen = SVGPathPen(gs, ntos=fmt)
    pen_x = 0.0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        name = order[info.codepoint]
        tx = x + (pen_x + pos.x_offset) * scale
        ty = baseline - pos.y_offset * scale
        gs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, tx, ty)))
        pen_x += pos.x_advance + tracking_em * upem
    width = (pen_x - tracking_em * upem) * scale
    return pen.getCommands(), width


def text_metrics(size):
    tt = TTFont(str(FONT))
    os2 = tt["OS/2"]
    upem = tt["head"].unitsPerEm
    return os2.sCapHeight * size / upem, os2.sxHeight * size / upem


# ---------------------------------------------------------------- compositions
IC = 108.0  # adaptive icon canvas (dp); safe zone is the central 66dp circle
ICON_MARK_H = 38.0  # bounding-box diagonal ~58dp, inside the 66dp safe circle


def icon_background() -> Scene:
    s = Scene(IC, IC)
    stage(s, key_at=(16, 6), key_r=84, back_at=(54, 58), back_r=40)
    return s


def icon_foreground() -> Scene:
    s = Scene(IC, IC)
    draw_mark(s, IC / 2, IC / 2, ICON_MARK_H)
    return s


BW, BH = 640.0, 360.0  # banner viewport; 320x180dp
BANNER_MARK_H = 148.0
CAP_RATIO = 0.40       # wordmark cap height / mark height


def banner_scene(dev: bool = False) -> Scene:
    s = Scene(BW, BH)
    mark_w = BANNER_MARK_H * MARK_ASPECT
    gap = BANNER_MARK_H * 0.24
    cap_unit, _ = text_metrics(100.0)
    size = 100.0 * CAP_RATIO * BANNER_MARK_H / cap_unit
    _, word_w = wordmark_path("Marquee", size, 0, 0)
    content_w = mark_w + gap + word_w   # stays inside 520 units, clear of the 14dp card clip
    left = (BW - content_w) / 2
    cy = BH / 2
    mcx = left + mark_w / 2
    stage(s, key_at=(110, -30), key_r=470, back_at=(mcx, cy + 10), back_r=170)
    draw_mark(s, mcx, cy, BANNER_MARK_H)
    cap, _ = text_metrics(size)
    d, _ = wordmark_path("Marquee", size, left + mark_w + gap, cy + cap / 2)
    s.add(d, Solid(WORD))
    if dev:  # debug builds: an unmistakable amber DEV tab in the top-right corner
        pill = LineString([(508, 52), (578, 52)]).buffer(22, quad_segs=12)
        s.add(poly_d(pill), Solid("#FFAB41"))
        dcap, _ = text_metrics(28.0)
        _, dw = wordmark_path("DEV", 28.0, 0, 0, tracking_em=0.04)
        d, _ = wordmark_path("DEV", 28.0, 543 - dw / 2, 52 + dcap / 2, tracking_em=0.04)
        s.add(d, Solid("#0E0D0D"))
    return s


def banner() -> Scene:
    return banner_scene()


# ---------------------------------------------------------------- outputs
def write(path: pathlib.Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    print("wrote", path)


def main():
    """Legacy entry point. The current identity is generated by design/brand/build_brand.py,
    which imports this module for its scene model, exporters and wordmark outlining."""
    ap = argparse.ArgumentParser(description=main.__doc__)
    ap.add_argument("--legacy-preview", type=pathlib.Path, metavar="DIR",
                    help="write SVG masters of the retired folded-light icon and banner to DIR")
    args = ap.parse_args()
    if not args.legacy_preview:
        ap.error("this script no longer writes app resources; run design/brand/build_brand.py "
                 "(or pass --legacy-preview DIR to render the retired mark)")
    bg, fg, bn = icon_background(), icon_foreground(), banner()
    write(args.legacy_preview / "icon-512.svg", to_svg(merge(bg, fg), 512, 512, view=(18, 18, 72, 72)))
    write(args.legacy_preview / "banner-640x360.svg", to_svg(bn, 640, 360))


if __name__ == "__main__":
    main()
