"""Generate or check docs/PUBLISH_MANIFEST.md: every file that is safe to publish.

"Safe to publish" means every file in the project tree that the repository's own .gitignore
files do not exclude. The list is computed by git itself (`git ls-files --others
--exclude-standard`) against a throwaway, empty repository created in a temporary directory, so:

- no .git directory is created in the project, and any enclosing repository is not touched;
- the user's global excludes file is ignored (core.excludesFile=/dev/null), so only the
  project's .gitignore rules apply.

Usage, from anywhere:

    uv run --no-project python tools/publish_manifest.py --write   # regenerate the manifest
    uv run --no-project python tools/publish_manifest.py --check   # exit 1 if it is stale (default)

The manifest lists itself without a size or hash (a file cannot contain its own hash); the
aggregate SHA-256 covers every other file.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST_REL = "docs/PUBLISH_MANIFEST.md"
MANIFEST = ROOT / MANIFEST_REL


def publishable() -> list[str]:
    with tempfile.TemporaryDirectory(prefix="marquee-manifest-") as tmp:
        git_dir = os.path.join(tmp, "git")
        env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
        env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull)
        subprocess.run(["git", "init", "-q", "--bare", git_dir], check=True, env=env)
        out = subprocess.run(
            ["git", f"--git-dir={git_dir}", f"--work-tree={ROOT}", "-c", f"core.excludesFile={os.devnull}",
             "ls-files", "--others", "--exclude-standard", "-z"],
            check=True, env=env, cwd=ROOT, capture_output=True).stdout
    paths = sorted({p for p in out.decode("utf-8").split("\0") if p} | {MANIFEST_REL},
                   key=lambda p: p.encode("utf-8"))
    for p in paths:
        if p != MANIFEST_REL and ((ROOT / p).is_symlink() or not (ROOT / p).is_file()):
            sys.exit(f"not a regular file: {p}")
    return paths


def sha256(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def render(paths: list[str]) -> str:
    rows, listing, total = [], [], 0
    for p in paths:
        if p == MANIFEST_REL:
            rows.append(f"| `{p}` | (this file) | (not self-hashed) |")
            continue
        f = ROOT / p
        size, digest = f.stat().st_size, sha256(f)
        total += size
        listing.append(f"{digest}  {p}\n")
        rows.append(f"| `{p}` | {size:,} | `{digest}` |")
    aggregate = hashlib.sha256("".join(listing).encode("utf-8")).hexdigest()
    head = f"""# Publish manifest

The exact set of files in this project that is intended to be published: every file not excluded
by the project's `.gitignore`. Generated by `tools/publish_manifest.py`; do not edit by hand.

How it is generated: `git ls-files --others --exclude-standard` runs against a throwaway, empty
bare repository in a temporary directory (`--git-dir=<tmp> --work-tree=<project root>`, global and
system git configuration and the global excludes file disabled). No `.git` directory is created in
the project and no enclosing repository is read or modified. Paths are sorted by their UTF-8 bytes.

Deliberately excluded by `.gitignore`, and therefore absent below: build outputs (`build/`,
`app/build/`, `.gradle/`, `.kotlin/`, `*.apk`, `*.aab`, `dist/`), machine-specific configuration
(`local.properties`, IDE folders), signing material (`*.jks`, `*.keystore`, `*.p12`, `*.pem`,
`keystore.properties`, `signing.properties`), Python caches (`__pycache__/`, `.pytest_cache/`,
`.venv/`), benchmark captures (`results/`, `bench/results/`) and optional maintainer exports
(`bench/evidence/`).

Check or regenerate (run from anywhere; `--check` exits 1 when this file is stale):

```sh
uv run --no-project python tools/publish_manifest.py --check
uv run --no-project python tools/publish_manifest.py --write
```

- Files: **{len(paths):,}** (including this manifest)
- Total size: **{total:,} bytes** (excluding this manifest)
- SHA-256 of the sorted listing: `{aggregate}`

The listing is the `sha256sum` output for every file except this manifest, one
`<sha256><two spaces><path><newline>` line per file in the order below, hashed as UTF-8.
This manifest cannot contain its own hash, so it is listed without one.

| Path | Bytes | SHA-256 |
|---|---:|---|
"""
    return head + "\n".join(rows) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help=f"regenerate {MANIFEST_REL}")
    mode.add_argument("--check", action="store_true", help="verify it is current (default)")
    args = ap.parse_args()
    text = render(publishable())
    if args.write:
        MANIFEST.write_text(text, encoding="utf-8")
        print(f"wrote {MANIFEST_REL}")
        return 0
    if MANIFEST.is_file() and MANIFEST.read_text(encoding="utf-8") == text:
        print(f"{MANIFEST_REL} is current")
        return 0
    print(f"{MANIFEST_REL} is stale; run: uv run --no-project python tools/publish_manifest.py --write",
          file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
